// Check emitted decoder/encoder rules independently of the capture metadata.
// Compiled Swift tests below exercise every declaration through the real decoder.
func checkSwiftNullRule(d *declaration, f field, source string) error {
	name := ident(f.JSON)
	switch f.NullPolicy {
	case wire.NullDistinct:
		decode := fmt.Sprintf("self.%s = c.contains(.%s) ? try c.decode(WireJSONValue.self, forKey: .%s) : nil", name, name, name)
		encode := fmt.Sprintf("try c.encodeIfPresent(%s, forKey: .%s)", name, name)
		if !strings.Contains(source, decode) || !strings.Contains(source, encode) {
			return fmt.Errorf("%s.%s: generated Swift collapses a distinct state", d.Swift, f.JSON)
		}
	case wire.NullForbidden:
		guard := fmt.Sprintf("if c.contains(.%s), try c.decodeNil(forKey: .%s)", name, name)
		if !strings.Contains(source, guard) {
			return fmt.Errorf("%s.%s: generated Swift accepts forbidden null", d.Swift, f.JSON)
		}
	case wire.NullCoalesced:
		if !strings.Contains(source, fmt.Sprintf("c.decodeIfPresent(%s.self, forKey: .%s)", f.Swift, name)) {
			return fmt.Errorf("%s.%s: missing coalesced decode rule", d.Swift, f.JSON)
		}
	default:
		return fmt.Errorf("%s.%s: no null declaration", d.Swift, f.JSON)
	}
	return nil
}

func TestEveryOptionalFieldDeclaresGeneratedNullStates(t *testing.T) {
	m, err := load(repoRoot(t))
	if err != nil {
		t.Fatal(err)
	}
	if err := m.prepare(); err != nil {
		t.Fatal(err)
	}
	count := 0
	for _, d := range m.Types {
		if d.AST == nil {
			continue
		}
		var generated bytes.Buffer
		emitStruct(&generated, d)
		for _, f := range d.Fields {
			if !f.Optional {
				continue
			}
			count++
			if err := checkSwiftNullRule(d, f, generated.String()); err != nil {
				t.Error(err)
			}
			// A declaration on every current optional field is mandatory, not
			// merely the two fields that exposed this bug in earlier releases.
			copy, err := load(repoRoot(t))
			if err != nil {
				t.Fatal(err)
			}
			st := copy.Types[d.Pkg+"."+d.Go].AST.Type.(*ast.StructType)
			for _, candidate := range st.Fields.List {
				if candidate.Names[0].Name != f.Go {
					continue
				}
				tag, err := strconv.Unquote(candidate.Tag.Value)
				if err != nil {
					t.Fatal(err)
				}
				policy := reflect.StructTag(tag).Get("null")
				candidate.Tag.Value = strconv.Quote(strings.Replace(tag, ` null:"`+policy+`"`, "", 1))
			}
			if err := copy.prepare(); err == nil {
				t.Errorf("%s.%s accepted a missing declaration", d.Swift, f.JSON)
			}
		}
	}
	if count == 0 {
		t.Fatal("no optional fields checked")
	}
	t.Logf("%d optional/nullable generated fields require declarations", count)
}

func TestNullRuleRejectsCollapsingGoShapeAndSwiftDecoder(t *testing.T) {
	m, err := load(repoRoot(t))
	if err != nil {
		t.Fatal(err)
	}
	d := m.Types["wire.PublicationResult"]
	for _, f := range d.AST.Type.(*ast.StructType).Fields.List {
		if f.Names[0].Name == "SelectionRevision" {
			f.Type = &ast.StarExpr{X: ast.NewIdent("string")}
		}
	}
	if err := m.prepare(); err == nil {
		t.Fatal("a collapsing *string was accepted for a distinct field")
	}
	m, err = load(repoRoot(t))
	if err != nil {
		t.Fatal(err)
	}
	if err := m.prepare(); err != nil {
		t.Fatal(err)
	}
	d = m.Types["wire.PublicationResult"]
	var generated bytes.Buffer
	emitStruct(&generated, d)
	for _, f := range d.Fields {
		if f.NullPolicy != wire.NullDistinct {
			continue
		}
		name := ident(f.JSON)
		good := fmt.Sprintf("self.%s = c.contains(.%s) ? try c.decode(WireJSONValue.self, forKey: .%s) : nil", name, name, name)
		bad := fmt.Sprintf("self.%s = try c.decodeIfPresent(WireJSONValue.self, forKey: .%s)", name, name)
		mutated := strings.Replace(generated.String(), good, bad, 1)
		if mutated == generated.String() {
			t.Fatal("decoder negative control did not mutate code")
		}
		if err := checkSwiftNullRule(d, f, mutated); err == nil {
			t.Fatal("collapsing Swift decoder escaped the rule check")
		}
	}
}

func TestNewOptionalFieldsCannotSkipNullPolicy(t *testing.T) {
	for _, tag := range []string{`json:"future,omitempty"`, `json:"future"`} {
		m, err := load(repoRoot(t))
		if err != nil {
			t.Fatal(err)
		}
		st := m.Types["wire.PublicationResult"].AST.Type.(*ast.StructType)
		st.Fields.List = append(st.Fields.List, &ast.Field{Names: []*ast.Ident{ast.NewIdent("FutureOptional")}, Type: &ast.StarExpr{X: ast.NewIdent("string")}, Tag: &ast.BasicLit{Value: strconv.Quote(tag)}})
		if err := m.prepare(); err == nil {
			t.Fatalf("new optional field without declaration accepted: %s", tag)
		}
	}
}

func TestUnmodeledOmissionCannotBypassNullRules(t *testing.T) {
	m, err := load(repoRoot(t))
	if err != nil {
		t.Fatal(err)
	}
	for _, f := range m.Types["wire.PluginInstallParams"].AST.Type.(*ast.StructType).Fields.List {
		if f.Names[0].Name == "Offline" {
			f.Tag.Value = strings.Replace(f.Tag.Value, "omitempty", "omitzero", 1)
		}
	}
	if err := m.prepare(); err == nil || !strings.Contains(err.Error(), "omitzero") {
		t.Fatalf("unmodeled omission bypassed field rules: %v", err)
	}
}
