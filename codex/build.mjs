import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname, join } from 'node:path';
const result = await build({ entryPoints: [new URL('./server.mjs',import.meta.url).pathname], outfile: new URL('./server.bundle.mjs',import.meta.url).pathname,
  bundle: true, platform:'node', format:'esm', target:'node22', minify:true,
  banner:{js:'// Generated by npm run build. Runtime dependencies are bundled for service-free plugin installs.\nimport { createRequire as __mpCreateRequire } from "node:module";const require=__mpCreateRequire(import.meta.url);'},
  legalComments:'eof', metafile:true });

const packages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  if (!input.includes('node_modules/')) continue;
  let dir=dirname(resolve(input));
  while(dir !== dirname(dir)) {
    try { const p=JSON.parse(await readFile(join(dir,'package.json'),'utf8')); if(p.name && p.version) { packages.set(p.name+'@'+p.version,{dir,p}); break; } } catch {}
    dir=dirname(dir);
  }
}
const notices=['# Third-party runtime notices\n\nGenerated by build.mjs from the bundled dependency graph. Versions are pinned in package-lock.json.'];
for(const [name,{dir,p}] of [...packages].sort(([a],[b])=>a.localeCompare(b))) {
  let license='License text retained in upstream package and bundle copyright headers.';
  for(const file of ['LICENSE','LICENSE.md','LICENSE.txt','license','license.md','LICENSE-MIT']) {
    try { license=await readFile(join(dir,file),'utf8'); break; } catch {}
  }
  notices.push('## '+name+'\n\nLicense: '+(p.license??'See upstream')+'\n\n'+license);
}
await writeFile(new URL('./THIRD-PARTY-NOTICES.md',import.meta.url),notices.join('\n\n').trimEnd()+'\n');
