"""Generate native consent identity declarations from consent-cli-pin.json."""
import argparse
import json
from pathlib import Path
import re

NATIVE = Path(__file__).resolve().parents[1]
SWIFT = NATIVE / 'ModelPlanAppIntegration/Sources/ModelPlanAppIntegration/CommunityConsentCLIIdentity.generated.swift'
SCENARIO = NATIVE / 'verification/u5-real-input-scenario.json'


def generated_files():
    pin = json.loads((NATIVE / 'consent-cli-pin.json').read_text())
    version = pin['version']
    sources = pin['sourceSHA256ByArchitecture']
    if (not re.fullmatch(r'\d+\.\d+\.\d+', version)
            or pin['release'] != 'https://github.com/modelplan/modelplan/releases/download/v' + version
            or set(sources) != {'arm64', 'x86_64'}
            or any(not re.fullmatch(r'[0-9a-f]{64}', value) for value in sources.values())):
        raise ValueError('Invalid native consent CLI pin')
    swift = ('// SPDX-License-Identifier: MIT\n'
             '// Generated by tools/generate-consent-cli-identity.py from consent-cli-pin.json. Do not edit.\n'
             'public extension CommunityConsentBundleIdentity {\n'
             f'    static let version = "{version}"\n'
             '    static let sourceSHA256ByArchitecture = [\n')
    swift += ''.join(f'        "{arch}": "{sources[arch]}",\n' for arch in ('arm64', 'x86_64'))
    swift += '    ]\n}\n'
    # Keep the scenario human-editable; only its release requirement is generated.
    scenario, count = re.subn(r'("requiredNativeCLIVersion": ")[^"]+(")',
                             lambda m: m[1] + version + m[2], SCENARIO.read_text())
    if count != 1:
        raise ValueError('Expected exactly one U5 native CLI requirement')
    return {SWIFT: swift, SCENARIO: scenario}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail on stale generated declarations without writing')
    args = parser.parse_args()
    for path, expected in generated_files().items():
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(f'Stale {path.relative_to(NATIVE)}; run python3 desktop/native/tools/generate-consent-cli-identity.py')
        else:
            path.write_text(expected)


if __name__ == '__main__':
    main()
