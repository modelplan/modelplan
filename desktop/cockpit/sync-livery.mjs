// Maker livery (D131, COL-2.1-18): the app copy of the website's shared maker colour table.
// The private site repo owns the table (src/shell/brandLivery.ts, guanbear/modelplans.ai). This public repo cannot read
// it at build time, so a copy of its colours is vendored in src/livery-shared.json and src/livery-table.ts is generated
// from that copy. Drift is caught in two steps:
//   node sync-livery.mjs --check                       offline (npm run check): the generated TS matches the vendored JSON
//   node sync-livery.mjs --check --source <file>       coordinator: the vendored JSON matches the shared table file
//   node sync-livery.mjs --source <file>               update the vendored JSON from the shared table, then regenerate
//   git -C <private checkout> show origin/main:src/shell/brandLivery.ts > /tmp/brandLivery.ts   (one way to get <file>)
// A maker's alternate shade comes from the shared table's `alt` field once it has one; until then it is derived here from
// the brand colour (same hue, lightness moved away from the nearer extreme), so the website can adopt the same rule.
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
const dir=fileURLToPath(new URL('./src/',import.meta.url));
const JSON_PATH=dir+'livery-shared.json',TS_PATH=dir+'livery-table.ts',CSS_PATH=fileURLToPath(new URL('../app/livery.css',import.meta.url));
// App-only accents with no maker row in the shared table (COL-2.1-15: grey-logo tool vendors).
const TOOLS={cursor:'#eef2f6',copilot:'#c08cff',opencode:'#b5d65a'};
const args=process.argv.slice(2),check=args.includes('--check'),si=args.indexOf('--source'),source=si>=0?args[si+1]:null;

const srgb=c=>c<=0.04045?c/12.92:((c+0.055)/1.055)**2.4,lin=c=>c<=0.0031308?12.92*c:1.055*c**(1/2.4)-0.055;
const toOklab=hex=>{const [r,g,b]=[1,3,5].map(i=>srgb(parseInt(hex.slice(i,i+2),16)/255));
 const l=Math.cbrt(0.4122214708*r+0.5363325363*g+0.0514459929*b),m=Math.cbrt(0.2119034982*r+0.6806995451*g+0.1073969566*b),s=Math.cbrt(0.0883024619*r+0.2817188376*g+0.6299787005*b);
 return [0.2104542553*l+0.793617785*m-0.0040720468*s,1.9779984951*l-2.428592205*m+0.4505937099*s,0.0259040371*l+0.7827717662*m-0.808675766*s];};
const fromOklab=([L,a,b])=>{const l=(L+0.3963377774*a+0.2158037573*b)**3,m=(L-0.1055613458*a-0.0638541728*b)**3,s=(L-0.0894841775*a-1.291485548*b)**3;
 return [4.0767416621*l-3.3077115913*m+0.2309699292*s,-1.2684380046*l+2.6097574011*m-0.3413193965*s,-0.0041960863*l-0.7034186147*m+1.707614701*s];};
const inGamut=v=>v.every(x=>x>=-0.0005&&x<=1.0005);
const hexOf=v=>'#'+v.map(x=>Math.round(Math.min(1,Math.max(0,lin(Math.min(1,Math.max(0,x)))))*255).toString(16).padStart(2,'0')).join('');
/** Alternate shade: same hue, lightness moved toward the far side (-0.28 from a light colour, +0.2 from a dark one), chroma reduced until it fits sRGB. */
export function deriveAlt(hex){
 const [L,a,b]=toOklab(hex),L2=L>=0.62?L-0.28:L+0.2;let k=1;
 for(;k>0;k-=0.05)if(inGamut(fromOklab([L2,a*k,b*k])))break;
 return hexOf(fromOklab([L2,a*Math.max(k,0),b*Math.max(k,0)]));
}
export function extract(text){
 const out={};
 for(const m of text.matchAll(/^ {2}([a-z0-9]+): L\(\{([\s\S]*?)^ {2}\}\),/gm)){
  const colour=/^\s*colour:\s*"(#[0-9a-fA-F]{6})"/m.exec(m[2])?.[1],alt=/^\s*alt:\s*"(#[0-9a-fA-F]{6})"/m.exec(m[2])?.[1];
  if(!colour)throw Error('no colour for '+m[1]);
  out[m[1]]=alt?{colour:colour.toLowerCase(),alt:alt.toLowerCase()}:{colour:colour.toLowerCase()};
 }
 if(Object.keys(out).length<8)throw Error('shared table not recognised');
 return out;
}
export function render(shared){
 const row=(k,colour,alt,altFrom)=>` ${k}:{colour:'${colour}',alt:'${alt}',altFrom:'${altFrom}'},`;
 const makers=Object.entries(shared.makers).map(([k,v])=>row(k,v.colour,v.alt??deriveAlt(v.colour),v.alt?'shared':'derived'));
 const tools=Object.entries(TOOLS).map(([k,c])=>row(k,c,deriveAlt(c),'derived'));
 return `// SPDX-License-Identifier: MIT
// GENERATED by sync-livery.mjs from livery-shared.json (a copy of the shared maker colour table, D131). Do not edit.
// Shared table: src/shell/brandLivery.ts in guanbear/modelplans.ai, sha256 ${shared.sourceSha256}.
export type Shade={readonly colour:string;readonly alt:string;readonly altFrom:'shared'|'derived'};
/** Makers of the shared table: real brand colour (black-and-white makers a light neutral) and one alternate shade. */
export const MAKERS:Readonly<Record<string,Shade>>={
${makers.join('\n')}
};
/** App-only accents of tool vendors that have no maker row (COL-2.1-15). */
export const TOOLS:Readonly<Record<string,Shade>>={
${tools.join('\n')}
};
`;
}
/** The developer colour variables the desktop stylesheet declares (the reserved theme.css keeps its frozen historical
 * bytes; this file is appended after it and wins). */
export function renderCss(shared){
 const vars=Object.entries(shared.makers).map(([k,v])=>`--mp-${k}: ${v.colour};`);
 return `/* SPDX-License-Identifier: MIT */\n/* GENERATED by cockpit/sync-livery.mjs from the shared maker colour table (D131). Do not edit. */\n:root {\n  ${vars.join('\n  ')}\n}\n`;
}
const read=p=>readFileSync(p,'utf8');
let shared=JSON.parse(read(JSON_PATH));
if(source){
 const text=read(source),next={sourceSha256:createHash('sha256').update(text).digest('hex'),makers:extract(text)};
 if(check){
  if(JSON.stringify(next)!==JSON.stringify(shared)){console.error('livery-shared.json differs from '+source+': run node sync-livery.mjs --source '+source);process.exit(1);}
 }else{shared=next;writeFileSync(JSON_PATH,JSON.stringify(shared,null,1)+'\n');}
}
const ts=render(shared),css=renderCss(shared);
if(check){
 if(read(TS_PATH)!==ts||read(CSS_PATH)!==css){console.error('src/livery-table.ts or app/livery.css is out of date: run node sync-livery.mjs');process.exit(1);}
 console.log('livery table consistent'+(source?' with the shared table':' with its vendored copy'));
}else{writeFileSync(TS_PATH,ts);writeFileSync(CSS_PATH,css);console.log('wrote src/livery-table.ts and app/livery.css');}
